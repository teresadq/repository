package service

import (
	"fmt"
	"html"
	"net/http"
	"sort"
	"strings"
	"time"

	"kkrepo-go/internal/store"
)

// serveMaven implements Maven layout storage and generated GA metadata.
func (s *Service) serveMaven(repository *store.Repository, request *Request) (*Response, error) {
	path := strings.TrimLeft(request.Path, "/")
	if repository.Type == "hosted" && (request.Method == http.MethodGet || request.Method == http.MethodHead) &&
		strings.HasSuffix(path, "maven-metadata.xml") {
		if _, ok := s.store.GetAsset(repository.Name, path); !ok {
			if body, ok := s.mavenMetadata(repository, path); ok {
				return bytesResponse(http.StatusOK, "application/xml", body, sha256Hex(body), time.Time{}, request.HeadOnly), nil
			}
		}
	}
	if repository.Type == "hosted" && (request.Method == http.MethodPut || request.Method == http.MethodPost) &&
		strings.HasSuffix(path, "maven-metadata.xml") {
		return nil, MethodNotAllowed("maven-metadata.xml is generated by the repository")
	}
	return s.serveGeneric(repository, request)
}

func (s *Service) mavenMetadata(repository *store.Repository, metadataPath string) ([]byte, bool) {
	dir := strings.TrimSuffix(metadataPath, "maven-metadata.xml")
	assets := s.store.ListAssets(repository.Name, dir)
	versionsSet := map[string]struct{}{}
	var lastUpdated time.Time
	for _, asset := range assets {
		if !strings.HasPrefix(asset.Path, dir) {
			continue
		}
		rest := strings.TrimPrefix(asset.Path, dir)
		if slash := strings.IndexByte(rest, '/'); slash > 0 {
			version := rest[:slash]
			if version != "" && !strings.HasSuffix(version, "/") {
				versionsSet[version] = struct{}{}
			}
		}
		if asset.UpdatedAt.After(lastUpdated) {
			lastUpdated = asset.UpdatedAt
		}
	}
	if len(versionsSet) == 0 {
		return nil, false
	}
	versions := make([]string, 0, len(versionsSet))
	for version := range versionsSet {
		versions = append(versions, version)
	}
	sort.Strings(versions)
	trimmed := strings.TrimSuffix(dir, "/")
	artifact := trimmed
	groupPath := ""
	if slash := strings.LastIndexByte(trimmed, '/'); slash >= 0 {
		artifact = trimmed[slash+1:]
		groupPath = strings.ReplaceAll(trimmed[:slash], "/", ".")
	}
	latest := versions[len(versions)-1]
	release := ""
	for index := len(versions) - 1; index >= 0; index-- {
		if !strings.Contains(versions[index], "-") {
			release = versions[index]
			break
		}
	}
	var builder strings.Builder
	builder.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n<metadata>\n")
	if groupPath != "" {
		fmt.Fprintf(&builder, "  <groupId>%s</groupId>\n", html.EscapeString(groupPath))
	}
	fmt.Fprintf(&builder, "  <artifactId>%s</artifactId>\n  <versioning>\n", html.EscapeString(artifact))
	fmt.Fprintf(&builder, "    <latest>%s</latest>\n", html.EscapeString(latest))
	if release != "" {
		fmt.Fprintf(&builder, "    <release>%s</release>\n", html.EscapeString(release))
	}
	builder.WriteString("    <versions>\n")
	for _, version := range versions {
		fmt.Fprintf(&builder, "      <version>%s</version>\n", html.EscapeString(version))
	}
	builder.WriteString("    </versions>\n")
	if !lastUpdated.IsZero() {
		fmt.Fprintf(&builder, "    <lastUpdated>%s</lastUpdated>\n", lastUpdated.UTC().Format("20060102150405"))
	}
	builder.WriteString("  </versioning>\n</metadata>\n")
	return []byte(builder.String()), true
}
