// serveHelm implements Helm chart storage, upload and a generated index.yaml.
func (s *Service) serveHelm(repository *store.Repository, request *Request) (*Response, error) {
	path := strings.TrimLeft(request.Path, "/")
	if repository.Type == "hosted" {
		switch {
		case request.Method == http.MethodGet || request.Method == http.MethodHead:
			if path == "index.yaml" {
				body := s.helmIndex(repository, request.BaseURL)
				return bytesResponse(http.StatusOK, "text/x-yaml", body, sha256Hex(body), time.Time{}, request.HeadOnly), nil
			}
		case request.Method == http.MethodPost:
			if path == "api/charts" {
				return s.helmUpload(repository, request)
			}
		case request.Method == http.MethodPut || request.Method == http.MethodDelete:
			if path == "index.yaml" {
				return nil, MethodNotAllowed("index.yaml is generated by the repository")
			}
		}
	}
	return s.serveGeneric(repository, request)
}

func (s *Service) helmIndex(repository *store.Repository, baseURL string) []byte {
	assets := s.store.ListAssets(repository.Name, ".tgz")
	type chartVersion struct {
		name    string
		version string
		path    string
		digest  string
		created time.Time
	}
	versions := make([]chartVersion, 0)
	for _, asset := range assets {
		if !strings.HasSuffix(asset.Path, ".tgz") {
			continue
		}
		name, version, ok := splitChartFilename(asset.Path)
		if !ok {
			name = asset.Module
			version = asset.Version
		}
		versions = append(versions, chartVersion{
			name: name, version: version, path: asset.Path, digest: asset.SHA256, created: asset.UpdatedAt,
		})
	}
	sort.Slice(versions, func(i, j int) bool {
		if versions[i].name != versions[j].name {
			return versions[i].name < versions[j].name
		}
		return versions[i].version < versions[j].version
	})
	var builder strings.Builder
	builder.WriteString("apiVersion: v1\nentries:\n")
	current := ""
	for _, entry := range versions {
		if entry.name != current {
			current = entry.name
			fmt.Fprintf(&builder, "  %s:\n", yamlScalar(entry.name))
		}
		url := "/repository/" + repository.Name + "/" + entry.path
		fmt.Fprintf(&builder, "  - apiVersion: v2\n    name: %s\n    version: %s\n    urls:\n    - %s\n    digest: %s\n    created: %s\n",
			yamlScalar(entry.name), yamlScalar(entry.version), yamlScalar(url),
			yamlScalar(entry.digest), entry.created.UTC().Format(time.RFC3339))
	}
	fmt.Fprintf(&builder, "generated: %s\n", time.Now().UTC().Format(time.RFC3339))
	return []byte(builder.String())
}

func (s *Service) helmUpload(repository *store.Repository, request *Request) (*Response, error) {
	if request.Body == nil {
		return nil, BadRequest("Chart upload is required")
	}
	reader := multipart.NewReader(io.LimitReader(request.Body, maxGenericUploadBytes), multipartBoundary(request.Header))
	form, err := reader.ReadForm(32 << 20)
	if err != nil {
		return nil, BadRequest("Invalid multipart chart upload")
	}
	defer form.RemoveAll()
	var file multipart.File
	var header *multipart.FileHeader
	for _, key := range []string{"chart", "file"} {
		if files := form.File[key]; len(files) > 0 {
			header = files[0]
			file, err = header.Open()
			if err != nil {
				return nil, BadRequest("Unable to read chart upload")
			}
			break
		}
	}
	if file == nil {
		return nil, BadRequest("Multipart field 'chart' is required")
	}
	defer file.Close()
	temp, err := os.CreateTemp(s.store.TempDir(), "helm-*.tgz")
	if err != nil {
		return nil, err
	}
	tempName := temp.Name()
	defer os.Remove(tempName)
	if _, err := io.Copy(temp, io.LimitReader(file, maxGenericUploadBytes)); err != nil {
		temp.Close()
		return nil, BadRequest("Unable to store chart upload")
	}
	temp.Close()
	name, version := inspectHelmChart(tempName)
	if name == "" {
		name, version, _ = splitChartFilename(header.Filename)
	}
	if name == "" || version == "" {
		return nil, BadRequest("Unable to determine chart name/version; include a valid Chart.yaml")
	}
	path := name + "-" + version + ".tgz"
	sum, size, _, err := s.store.SaveBlobFile(tempName)
	if err != nil {
		return nil, err
	}
	now := s.now()
	asset := &store.Asset{
		Repository: repository.Name, Format: "helm", Path: path, Module: name, Version: version,
		Kind: "chart", ContentType: "application/gzip", Size: size, SHA256: sum, Source: "hosted",
		CreatedAt: now, UpdatedAt: now,
	}
	component := &store.Component{
		Repository: repository.Name, Format: "helm", Module: name, Version: version,
		Kind: "helm-chart", Time: now, CreatedAt: now, UpdatedAt: now,
	}
	if err := s.store.PutAsset(asset, component, true); err != nil {
		return nil, err
	}
	body, _ := jsonBytes(map[string]any{"saved": true, "name": name, "version": version, "path": path})
	return bytesResponse(http.StatusCreated, "application/json", body, "", time.Time{}, request.HeadOnly), nil
}

func splitChartFilename(path string) (string, string, bool) {
	base := path
	if slash := strings.LastIndexByte(base, '/'); slash >= 0 {
		base = base[slash+1:]
	}
	base = strings.TrimSuffix(base, ".tgz")
	for index := len(base) - 1; index > 0; index-- {
		if base[index] == '-' && index+1 < len(base) && base[index+1] >= '0' && base[index+1] <= '9' {
			return base[:index], base[index+1:], true
		}
	}
	return "", "", false
}

func inspectHelmChart(path string) (string, string) {
	file, err := os.Open(path)
	if err != nil {
		return "", ""
	}
	defer file.Close()
	gzipReader, err := gzip.NewReader(file)
	if err != nil {
		return "", ""
	}
	defer gzipReader.Close()
	tarReader := tar.NewReader(gzipReader)
	for {
		header, err := tarReader.Next()
		if err != nil {
			return "", ""
		}
		if header.Typeflag != tar.TypeReg {
			continue
		}
		base := header.Name
		if slash := strings.LastIndexByte(base, '/'); slash >= 0 {
			base = base[slash+1:]
		}
		if base != "Chart.yaml" {
			continue
		}
		content, err := io.ReadAll(io.LimitReader(tarReader, 1<<20))
		if err != nil {
			return "", ""
		}
		name, version := "", ""
		for _, line := range strings.Split(string(content), "\n") {
			trimmed := strings.TrimSpace(line)
			if strings.HasPrefix(trimmed, "name:") && name == "" {
				name = strings.TrimSpace(strings.TrimPrefix(trimmed, "name:"))
				name = strings.Trim(name, `"'`)
			}
			if strings.HasPrefix(trimmed, "version:") && version == "" {
				version = strings.TrimSpace(strings.TrimPrefix(trimmed, "version:"))
				version = strings.Trim(version, `"'`)
			}
		}
		return name, version
	}
}

func multipartBoundary(header http.Header) string {
	_, params, err := mime.ParseMediaType(header.Get("Content-Type"))
	if err != nil {
		return ""
	}
	return params["boundary"]
}

func yamlScalar(value string) string {
	if value == "" {
		return `""`
	}
	return value
}
